// https://eco.mtk.nao.ac.jp/koyomi/yoko/
export const OFFICIAL_NEW_MOONS_JST = [
  "2025-12-20T10:43:00+09:00",
  "2026-01-19T04:52:00+09:00", "2026-02-17T21:01:00+09:00",
  "2026-03-19T10:23:00+09:00", "2026-04-17T20:52:00+09:00",
  "2026-05-17T05:01:00+09:00", "2026-06-15T11:54:00+09:00",
  "2026-07-14T18:44:00+09:00", "2026-08-13T02:37:00+09:00",
  "2026-09-11T12:27:00+09:00", "2026-10-11T00:50:00+09:00",
  "2026-11-09T16:02:00+09:00", "2026-12-09T09:52:00+09:00",
  "2027-01-08T05:24:00+09:00", "2027-02-07T00:56:00+09:00",
  "2027-03-08T18:29:00+09:00", "2027-04-07T08:51:00+09:00",
  "2027-05-06T19:59:00+09:00", "2027-06-05T04:40:00+09:00",
  "2027-07-04T12:02:00+09:00", "2027-08-02T19:05:00+09:00",
  "2027-09-01T02:41:00+09:00", "2027-09-30T11:36:00+09:00",
  "2027-10-29T22:37:00+09:00", "2027-11-28T12:24:00+09:00",
  "2027-12-28T05:12:00+09:00"
].map(Date.parse);

export function officialLunarAgeDays(date) {
  const time = date.getTime();
  const previous = [...OFFICIAL_NEW_MOONS_JST].reverse().find((phaseTime) => phaseTime <= time);
  if (previous === undefined || time > Date.parse("2027-12-31T23:59:59+09:00")) return null;
  return (time - previous) / 86400000;
}
